#!/usr/bin/env node
// The hero's first paint (D-024, #13 A1 and A2): the X-T5 line drawing per band, generated from the 3D model.
//   node src/gl/camera/build/drawing.mjs [--preview <dir>]
// Reads the framing of every band from public/posters/camera/posters.json (the hero pose, FOV 28, the posters'
// aspect), runs drawing-page.js in Chrome on the reference host's GPU and writes, next to the camera posters:
//   public/posters/camera/drawing-<band>.svg   curated strokes in two weights, hidden lines removed
//   public/posters/camera/drawing.json         the manifest: per band its file, aspect, stroke counts and bytes
// The SVG carries strokes only: the undeveloped print ground under it is CSS (Hero.astro), so at T0 the ground can
// hand over to GL's own veil while the strokes stay on top and fade with it. Re-run after a model or pose change
// (and after the posters, whose framing it reads). Owner: W-S1, then W-C14 (re-bake on m2 changes).
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { launch, repo, serve, SOFTWARE } from '../../../../scripts/build/posters/harness.mjs';

const args = process.argv.slice(2);
const opt = (k, d) => (args.includes(k) ? args[args.indexOf(k) + 1] : d);
const OUT = resolve(repo, 'public/posters/camera');
const preview = opt('--preview', null);
/** The strokes' colour on the teal-grey ground: a pale, slightly cool white (the drawing is light on the veil). */
const STROKE = '#DDE8E5';
const WEIGHT = { heavy: 1.3, light: 0.75 };

const posters = JSON.parse(readFileSync(join(OUT, 'posters.json'), 'utf8'));
const sha = (b) => createHash('sha256').update(b).digest('hex');

function svgOf(r) {
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${r.width} ${r.height}" width="${r.width}" height="${Math.round(r.height)}" fill="none" stroke="${STROKE}" stroke-linecap="round" stroke-linejoin="round">`,
    `<path stroke-width="${WEIGHT.light}" stroke-opacity="0.82" vector-effect="non-scaling-stroke" d="${r.light}"/>`,
    `<path stroke-width="${WEIGHT.heavy}" vector-effect="non-scaling-stroke" d="${r.heavy}"/>`,
    '</svg>',
  ].join('');
}

const { server, origin } = await serve();
const browser = await launch();
const manifest = {
  $comment: 'Generated by src/gl/camera/build/drawing.mjs from public/models/camera_xt_lod0.glb in the posters.json framing. The hero shows drawing-<band>.svg on the undeveloped ground before GL (W-D012 data-cam=drawing).',
  model: { file: 'public/models/camera_xt_lod0.glb', sha256: sha(readFileSync(join(repo, 'public/models/camera_xt_lod0.glb'))) },
  posters: { sha256: sha(readFileSync(join(OUT, 'posters.json'))) },
  stroke: STROKE,
  weightsCssPx: WEIGHT,
  renderer: null,
  bands: {},
};
try {
  const ctx = await browser.newContext({ viewport: { width: 800, height: 600 }, deviceScaleFactor: 1 });
  for (const [band, framing] of Object.entries(posters.bands)) {
    const page = await ctx.newPage();
    const errors = [];
    page.on('pageerror', (e) => errors.push(String(e)));
    page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
    const { posters: _p, ...frame } = framing;
    void _p;
    const qs = new URLSearchParams({ framing: JSON.stringify(frame), opts: JSON.stringify({}) });
    await page.goto(`${origin}/src/gl/camera/build/drawing.html?${qs}`);
    await page.waitForFunction(() => window.__done !== undefined, null, { timeout: 180_000 });
    const r = await page.evaluate(() => window.__done);
    if (r.error) throw new Error(`${band}: ${r.error}`);
    if (errors.length) throw new Error(`${band}: console errors: ${errors.join(' | ')}`);
    if (SOFTWARE.test(r.renderer)) throw new Error(`${band}: software renderer ${r.renderer}`);
    manifest.renderer = r.renderer;
    const svg = svgOf(r);
    const file = `drawing-${band}.svg`;
    writeFileSync(join(OUT, file), `${svg}\n`);
    manifest.bands[band] = { file, aspect: framing.aspect, viewBox: [0, 0, r.width, r.height], strokes: { heavy: r.stats.heavy, light: r.stats.light }, bytes: Buffer.byteLength(svg), stats: r.stats };
    console.log(`${file.padEnd(22)} heavy ${r.stats.heavy}  light ${r.stats.light}  (edges ${r.stats.edges}, runs ${r.stats.runs}, chained ${r.stats.chained})  ${(Buffer.byteLength(svg) / 1024).toFixed(1)} kB`);
    await page.close();
    if (preview) {
      mkdirSync(preview, { recursive: true });
      const w = 900;
      const h = Math.round(w / framing.aspect);
      const poster = framing.posters.lod0.find((p) => p.w === 1200) ?? framing.posters.lod0[0];
      const uri = `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`;
      const pv = await ctx.newPage();
      await pv.setViewportSize({ width: w * 2, height: h });
      await pv.setContent(`<html><body style="margin:0;display:flex"><div style="position:relative;width:${w}px;height:${h}px;background:#2D4547"><img src="${uri}" style="position:absolute;inset:0;width:100%;height:100%"></div><div style="position:relative;width:${w}px;height:${h}px;background:#E3E6E6"><img src="${origin}/public/posters/camera/${poster.webp}" style="position:absolute;inset:0;width:100%;height:100%;object-fit:contain"><img src="${uri}" style="position:absolute;inset:0;width:100%;height:100%;filter:invert(1) sepia(1) saturate(8) hue-rotate(320deg)"></div></body></html>`);
      await pv.waitForLoadState('networkidle');
      await pv.screenshot({ path: join(preview, `drawing-${band}.png`) });
      await pv.close();
    }
  }
  writeFileSync(join(OUT, 'drawing.json'), `${JSON.stringify(manifest, null, 1)}\n`);
  console.log(`renderer: ${manifest.renderer}`);
} finally {
  await browser.close();
  server.close();
}
