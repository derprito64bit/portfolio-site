#!/usr/bin/env node
// Tokens build (W-F). Zero dependencies, deterministic: the same content/tokens.json always gives the same bytes.
// Emits two outputs (W-V0a, D-049: the Manor seam files are retired):
//   tokens.css          -> src/styles/tokens.css   (site custom properties, committed)
//   tokens.js           -> src/lib/tokens.js       (runtime constants, committed)
// Usage:
//   node scripts/build/tokens.mjs                 write tokens.css and tokens.js into src/
//   node scripts/build/tokens.mjs --out <dir>     write both files into <dir> only (determinism check)
//   node scripts/build/tokens.mjs --check         exit 1 if the committed src/ outputs differ from a fresh build
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const HEADER = 'generated by scripts/build/tokens.mjs from content/tokens.json. Do not edit.';

// ---------------------------------------------------------------- springs (W-D010)
/** Unit step response of a damped spring at mass 1 (exact, underdamped). */
export function springStep(hz, zeta, tSeconds) {
  const w = 2 * Math.PI * hz;
  const wd = w * Math.sqrt(1 - zeta * zeta);
  return 1 - Math.exp(-zeta * w * tSeconds) * (Math.cos(wd * tSeconds) + ((zeta * w) / wd) * Math.sin(wd * tSeconds));
}

/** Derived numbers for one spring, from (Hz, zeta) only. */
export function springFacts(hz, zeta) {
  const w = 2 * Math.PI * hz;
  const overshoot = Math.exp((-zeta * Math.PI) / Math.sqrt(1 - zeta * zeta));
  let settle2 = 0;
  let settle01 = 0;
  for (let i = 0; i <= 300000; i++) {
    const t = i * 1e-5;
    const e = Math.abs(springStep(hz, zeta, t) - 1);
    if (e > 0.02) settle2 = t;
    if (e > 0.001) settle01 = t;
  }
  return { stiffness: w * w, damping: 2 * zeta * w, overshootPct: overshoot * 100, settle2Ms: settle2 * 1000, settle01Ms: settle01 * 1000 };
}

const num = (x, digits = 4) => {
  const s = x.toFixed(digits);
  return s.includes('.') ? s.replace(/0+$/, '').replace(/\.$/, '') : s;
};

/** CSS linear() easing for a spring over durationMs: 41 evenly spaced samples, the last pinned to 1. */
export function cssLinear(hz, zeta, durationMs, samples = 40) {
  const pts = [];
  for (let i = 0; i <= samples; i++) {
    const t = (durationMs / 1000) * (i / samples);
    pts.push(i === samples ? '1' : num(springStep(hz, zeta, t)));
  }
  return `linear(${pts.join(', ')})`;
}

function checkSprings(springs) {
  const problems = [];
  for (const [name, s] of Object.entries(springs)) {
    if (name.startsWith('$')) continue;
    const f = springFacts(s.hz, s.zeta);
    const near = (a, b, tol) => Math.abs(a - b) <= tol;
    if (!near(f.stiffness, s.stiffness, 0.1)) problems.push(`${name}: stiffness ${s.stiffness} but (2*pi*hz)^2 = ${f.stiffness.toFixed(2)}`);
    if (!near(f.damping, s.damping, 0.01)) problems.push(`${name}: damping ${s.damping} but 2*zeta*w = ${f.damping.toFixed(3)}`);
    if (!near(f.overshootPct, s.overshootPct, 0.1)) problems.push(`${name}: overshootPct ${s.overshootPct} but analytic ${f.overshootPct.toFixed(2)}`);
    if (!near(f.settle2Ms, s.settle2Ms, 2)) problems.push(`${name}: settle2Ms ${s.settle2Ms} but analytic ${f.settle2Ms.toFixed(1)}`);
    if (s.cssLinearMs < f.settle01Ms) problems.push(`${name}: cssLinearMs ${s.cssLinearMs} ends before the spring settles to 0.1% (${f.settle01Ms.toFixed(0)} ms)`);
  }
  return problems;
}

// ---------------------------------------------------------------- outputs
const kebab = (s) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);
const block = (selector, vars, indent = '') =>
  `${indent}${selector} {\n${vars.map(([k, v]) => `${indent}  ${k}: ${v};`).join('\n')}\n${indent}}\n`;

function schemeVars(c, scheme) {
  const p = c[scheme];
  const roles = c.roles[scheme];
  const vars = [
    ['--table', p.table], ['--table-lit', p['table-lit']], ['--paper', p.paper], ['--rule', p.rule],
    ['--ink', p.ink], ['--ink-2', p['ink-2']],
  ];
  if (p.proof) vars.splice(3, 0, ['--proof', p.proof]);
  const resolve = (v) => (v === 'amber' ? 'var(--amber)' : v === 'amber-deep' ? 'var(--amber-deep)' : v === 'ink' ? 'var(--ink)' : v === 'ink-2' ? 'var(--ink-2)' : v);
  // Ink on amber is always the dark ink (7.72:1), whatever the scheme's --ink is.
  for (const [k, v] of Object.entries(roles)) vars.push([k, k === '--on-accent' ? c.accent['on-accent'] : resolve(v)]);
  const pair = scheme === 'light' ? c.focusBySurface.lightSurfaces : c.focusBySurface.darkSurfaces;
  vars.push(['--focus', pair['--focus']], ['--focus-halo', pair['--focus-halo']]);
  return vars;
}

export function buildTokens(t) {
  const problems = checkSprings(t.motion.springs);
  if (problems.length) throw new Error(`content/tokens.json spring table is inconsistent:\n  ${problems.join('\n  ')}`);

  const c = t.colour;
  const fam = t.type.families;
  const springs = Object.entries(t.motion.springs).filter(([k]) => !k.startsWith('$'));
  const lightSurface = c.focusBySurface.lightSurfaces;
  const darkSurface = c.focusBySurface.darkSurfaces;

  // ---------- tokens.css ----------
  const rootVars = [
    ['color-scheme', 'light dark'],
    ...schemeVars(c, 'light'),
    ['--darkroom', c.door.darkroom], ['--on-dark', c.door['on-dark']], ['--on-dark-2', c.door['on-dark-2']], ['--on-dark-3', c.door['on-dark-3']],
    ['--amber', c.accent.amber], ['--amber-deep', c.accent['amber-deep']], ['--brass', c.accent.brass.value],
    ['--ink-drip', c.door.darkroom],
    ['--focus-light', lightSurface['--focus']], ['--focus-halo-light', lightSurface['--focus-halo']],
    ['--focus-dark', darkSurface['--focus']], ['--focus-halo-dark', darkSurface['--focus-halo']],
    ['--font-mark', '"BG Mark", "BG Mark Fallback", system-ui, sans-serif'],
    ['--font-display', '"BG Display", "BG Display Fallback", system-ui, sans-serif'],
    ['--font-text', '"BG Text", "BG Text Fallback", system-ui, sans-serif'],
    ['--font-edge', '"Edge Mono", "Edge Mono Fallback", ui-monospace, monospace'],
    ['--type-wordmark', t.type.roles.wordmark.size.replace(/, container = .*$/, '')],
    ['--type-display', t.type.roles.display.css], ['--type-index', t.type.roles.index.css], ['--type-title', t.type.roles.title.css],
    ['--type-lede', t.type.roles.lede.css], ['--type-body', t.type.roles.body.css],
    ['--type-ui', `${t.type.roles.ui.px / 16}rem`], ['--type-edge', `${t.type.roles.edge.px / 16}rem`],
    ['--type-floor', `${t.type.floorPx}px`],
    ['--measure-body', t.type.roles.body.measure], ['--measure-lede', t.type.roles.lede.measure],
    ...t.space.scale.map((v, i) => [`--space-${i + 1}`, `${v}px`]),
    ['--gutter', t.space.gutter], ['--content-max', t.space.contentMax], ['--rise', t.space.rise],
    ['--radius-ui', t.radius.ui], ['--radius-print', t.radius.print],
    ['--focus-ring-width', '3px'], ['--focus-halo-width', '2px'], ['--focus-offset', t.focus.offset],
    ['--ease-out', t.motion.ease.out], ['--ease-in-out-cubic', t.motion.ease.inOutCubic],
    ...Object.entries(t.motion.durationsMs).map(([k, v]) => [`--dur-${kebab(k)}`, `${v}ms`]),
    // W-D011's flash shape: it peaks at peakOpacity, peakAtMs into its durationsMs.flash.
    ['--flash-peak-at', `${t.motion.flash.peakAtMs}ms`], ['--flash-peak-opacity', String(t.motion.flash.peakOpacity)],
    ...springs.flatMap(([name, s]) => [[`--spring-${name}`, cssLinear(s.hz, s.zeta, s.cssLinearMs)], [`--spring-${name}-ms`, `${s.cssLinearMs}ms`]]),
    ...Object.entries(t.z).map(([k, v]) => [`--z-${kebab(k)}`, String(v)]),
  ];
  const darkVars = schemeVars(c, 'dark');
  const lightSurfaceVars = [
    ['--ink', c.light.ink], ['--ink-2', c.light['ink-2']], ['--placeholder', c.light['ink-2']],
    ['--accent-text', 'var(--amber-deep)'], ['--focus', lightSurface['--focus']], ['--focus-halo', lightSurface['--focus-halo']],
  ];
  const darkSurfaceVars = [
    ['--ink', c.door['on-dark']], ['--ink-2', c.door['on-dark-2']], ['--placeholder', c.door['on-dark-2']],
    ['--accent-text', 'var(--amber)'], ['--focus', darkSurface['--focus']], ['--focus-halo', darkSurface['--focus-halo']],
  ];
  const css = [
    `/* ${HEADER} */`,
    `/* Breakpoints (media queries cannot read custom properties): ${Object.entries(t.breakpoints).map(([k, v]) => `${k} ${v}`).join('; ')}. */`,
    block(':root', rootVars),
    `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme="light"])', darkVars, '  ')}}\n`,
    block(':root[data-theme="dark"]', darkVars),
    `/* Focus and ink by surface, not by scheme (W-D032): ${lightSurface.surfaces.join(', ')} | ${darkSurface.surfaces.join(', ')}. */`,
    block('[data-surface="light"]', lightSurfaceVars),
    block('[data-surface="dark"]', darkSurfaceVars),
  ].join('\n');

  // ---------- tokens.js ----------
  const springTable = Object.fromEntries(
    springs.map(([name, s]) => [name, { hz: s.hz, zeta: s.zeta, mass: 1, stiffness: s.stiffness, damping: s.damping, overshootPct: s.overshootPct, settle2Ms: s.settle2Ms, cssLinearMs: s.cssLinearMs, css: cssLinear(s.hz, s.zeta, s.cssLinearMs) }]),
  );
  const exp = (name, value) => `export const ${name} = /*#__PURE__*/ Object.freeze(${JSON.stringify(value, null, 2)});\n`;
  const js = [
    `// ${HEADER}`,
    '// Named exports so a bundle keeps only what it reads.',
    exp('springs', springTable),
    exp('durations', t.motion.durationsMs),
    exp('flash', { peakAtMs: t.motion.flash.peakAtMs, peakOpacity: t.motion.flash.peakOpacity }),
    exp('heroTimeline', t.motion.heroTimelineMs),
    exp('develop', t.motion.develop),
    exp('ease', t.motion.ease),
    exp('z', t.z),
    exp('breakpoints', t.breakpoints),
    // tiers.never names the two navigator fields tier code must not read; it stays in the source only, so a grep of
    // src/ for them finds nothing (W-D017).
    exp('tiers', Object.fromEntries(Object.entries(t.tiers).filter(([k]) => k !== 'never'))),
    exp('stage', t.stage),
    exp('layout', t.layout),
    exp('monogram', t.monogram),
    exp('filmLooks', t.filmLooks),
    exp('predicates', t.predicates),
    exp('colour', { light: c.light, dark: c.dark, door: c.door, accent: { amber: c.accent.amber, amberDeep: c.accent['amber-deep'], onAccent: c.accent['on-accent'], brass: c.accent.brass.value } }),
    "export const MOTION_KEY = 'ion.motion';\n",
  ].join('\n');

  return {
    'tokens.css': css,
    'tokens.js': js,
  };
}

// ---------------------------------------------------------------- CLI
const SRC_TARGETS = { 'tokens.css': 'src/styles/tokens.css', 'tokens.js': 'src/lib/tokens.js' };

export function readSource() {
  return JSON.parse(readFileSync(join(ROOT, 'content/tokens.json'), 'utf8'));
}

function write(path, text) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const opt = (name) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : null; };
  try {
    const files = buildTokens(readSource());
    if (args.includes('--check')) {
      const stale = Object.entries(SRC_TARGETS).filter(([name, rel]) => {
        try { return readFileSync(join(ROOT, rel), 'utf8') !== files[name]; } catch { return true; }
      });
      if (stale.length) {
        console.error(`tokens: ${stale.map(([, rel]) => rel).join(', ')} out of date; run npm run tokens`);
        process.exit(1);
      }
      console.log('tokens: src outputs match content/tokens.json');
    } else if (opt('--out')) {
      const dir = resolve(opt('--out'));
      for (const [name, text] of Object.entries(files)) write(join(dir, name), text);
      console.log(`tokens: wrote ${Object.keys(files).length} files to ${dir}`);
    } else {
      for (const [name, rel] of Object.entries(SRC_TARGETS)) write(join(ROOT, rel), files[name]);
      console.log(`tokens: wrote ${Object.values(SRC_TARGETS).join(', ')}`);
    }
  } catch (e) {
    console.error(`tokens: ${e.message}`);
    process.exit(1);
  }
}
