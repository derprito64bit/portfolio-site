// wire.mjs (W-C13): wireframe posters of the camera with build-measured triangle counts (W-D020 'Show the mesh':
// the static tier swaps to a pre-rendered wireframe poster and prints the count read from the geometry at build).
//
//   node scripts/build/posters/wire.mjs [--out public/posters/wire] [--widths 800,1600] [--allow-software]
//
// Same stage as the camera posters (stage.js framing from tokens.stage, three r186 in Chrome on the reference host's
// GPU), LOD0 in flat proof grey with every triangle edge in ink. Writes wire-<band>-<w>.{avif,webp} and wire.json:
// the triangle count of every shipped LOD, measured on the loaded geometry (three r186) and cross-checked against
// glbstat (the GLB's own accessor counts); a mismatch fails the build.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import sharp from "sharp";
import { REVISION } from "three";
import { glbStat } from "../glb/glbstat.mjs";
import { launch, repo, runPage, serve, SOFTWARE, stageTokens } from "./harness.mjs";

const args = process.argv.slice(2);
const opt = (k, d) => (args.includes(k) ? args[args.indexOf(k) + 1] : d);
const out = resolve(repo, opt("--out", "public/posters/wire"));
const widths = opt("--widths", "800,1600").split(",").map(Number);
const FILES = { lod0: "camera_xt_lod0.glb", lod1: "camera_xt_lod1.glb", manor: "camera_xt_manor.glb" };

async function main() {
  const { file: tokensFile, fovDeg, poses } = stageTokens();
  mkdirSync(out, { recursive: true });
  const { server, origin } = await serve();
  const browser = await launch();
  try {
    const context = await browser.newContext({ viewport: { width: 1600, height: 1200 }, deviceScaleFactor: 1 });
    const framed = await runPage(context, origin, { mode: "frame", poses, fov: String(fovDeg), margin: "0.06" });
    const manifest = {
      $comment: "Generated by scripts/build/posters/wire.mjs. Triangle counts are measured on the shipped GLBs.",
      three: REVISION, tokens: relative(repo, tokensFile).replace(/\\/g, "/"), renderer: null, models: {}, bands: {},
    };
    for (const [lod, file] of Object.entries(FILES)) {
      const r = await runPage(context, origin, { mode: "wire", framing: framed.bands.split, w: "64", file });
      const stat = glbStat(readFileSync(join(repo, "public/models", file)), file);
      if (r.tris !== stat.tris) throw new Error(`${file}: three counts ${r.tris} tris, glbstat ${stat.tris}`);
      manifest.models[lod] = { file: `public/models/${file}`, tris: r.tris, draws: stat.draws };
    }
    for (const [band, framing] of Object.entries(framed.bands)) {
      const files = [];
      for (const w of widths) {
        const r = await runPage(context, origin, { mode: "wire", framing, w: String(w), lod: "0" });
        if (SOFTWARE.test(r.renderer) && !args.includes("--allow-software")) throw new Error(`software renderer: ${r.renderer}`);
        manifest.renderer = r.renderer;
        const png = Buffer.from(r.png.split(",")[1], "base64");
        const name = `wire-${band}-${w}`;
        const webp = await sharp(png).webp({ quality: 82, alphaQuality: 100, effort: 6 }).toBuffer();
        const avif = await sharp(png).avif({ quality: 60, effort: 6, chromaSubsampling: "4:4:4" }).toBuffer();
        writeFileSync(join(out, `${name}.webp`), webp);
        writeFileSync(join(out, `${name}.avif`), avif);
        files.push({ w: r.w, h: r.h, avif: `${name}.avif`, webp: `${name}.webp`, avifBytes: avif.length, webpBytes: webp.length });
        console.log(`${name.padEnd(20)} ${r.w}x${r.h}  avif ${(avif.length / 1024).toFixed(1)} kB  webp ${(webp.length / 1024).toFixed(1)} kB`);
      }
      manifest.bands[band] = { aspect: framing.aspect, lod: 0, tris: manifest.models.lod0.tris, posters: files };
    }
    writeFileSync(join(out, "wire.json"), JSON.stringify(manifest, null, 1) + "\n");
    console.log(`tris: ${Object.entries(manifest.models).map(([k, m]) => `${k} ${m.tris}`).join(", ")}\nwrote ${join(out, "wire.json")}`);
  } finally {
    await browser.close();
    server.close();
  }
}

main().catch((e) => { console.error(e); process.exit(1); });
