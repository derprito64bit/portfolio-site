// render.mjs (W-C13): camera posters per band, rendered by three r186 in Chrome on the reference host's GPU through
// the same stage code the live canvas uses (stage.js framing, the look module), so a poster equals the first GL frame.
//
//   node scripts/build/posters/render.mjs [--out public/posters/camera] [--widths 480,800,1200,1600]
//        [--lod1-widths 360,600] [--look <module, default scripts/build/posters/look.js>] [--quality 90] [--png]
//        [--margin 0.06 (empty band around the model per side, as a share of the frame height)]
//        [--allow-software]
//
// Writes <out>/posters.json and, per band, one poster set per LOD: camera-<band>-<w>.{avif,webp} from LOD0 and
// camera-<band>-lod1-<w>.{avif,webp} from LOD1. LOD1 frames are under 600 device px wide (tokens.stage.lod), so its
// set stops at 600 px. The live stage reads posters.json: applyFraming() sets its camera, containRect() its viewport,
// and posterSet() picks the set of the LOD it is about to draw. Re-run after a model, look or pose change.
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import sharp from "sharp";
import { REVISION } from "three";
import { launch, repo, runPage, serve, SOFTWARE, stageTokens } from "./harness.mjs";

const args = process.argv.slice(2);
const opt = (k, d) => (args.includes(k) ? args[args.indexOf(k) + 1] : d);
const out = resolve(repo, opt("--out", "public/posters/camera"));
const WIDTHS = {
  lod0: opt("--widths", "480,800,1200,1600").split(",").map(Number),
  lod1: opt("--lod1-widths", "360,600").split(",").map(Number),
};
const look = opt("--look", null);
const quality = Number(opt("--quality", 90));
const margin = opt("--margin", "0.06");

async function encode(png, base) {
  const img = sharp(png);
  const webp = await img.clone().webp({ quality, alphaQuality: 100, effort: 6, smartSubsample: true }).toBuffer();
  const avif = await img.clone().avif({ quality: quality - 25, effort: 6, chromaSubsampling: "4:4:4" }).toBuffer();
  writeFileSync(`${base}.webp`, webp);
  writeFileSync(`${base}.avif`, avif);
  return { webpBytes: webp.length, avifBytes: avif.length };
}

const sha = (f) => createHash("sha256").update(readFileSync(join(repo, f))).digest("hex");

async function main() {
  const { file: tokensFile, fovDeg, poses } = stageTokens();
  mkdirSync(out, { recursive: true });
  const { server, origin } = await serve();
  const browser = await launch();
  try {
    const context = await browser.newContext({ viewport: { width: 1600, height: 1200 }, deviceScaleFactor: 1 });
    const lookUrl = look ? `/${relative(repo, resolve(repo, look)).replace(/\\/g, "/")}` : undefined;
    const framed = await runPage(context, origin, { mode: "frame", poses, fov: String(fovDeg), margin });
    const manifest = {
      $comment: "Generated by scripts/build/posters/render.mjs. The live stage frames the camera from this file.",
      three: REVISION, tokens: relative(repo, tokensFile).replace(/\\/g, "/"),
      models: { lod0: { file: "public/models/camera_xt_lod0.glb", sha256: sha("public/models/camera_xt_lod0.glb") },
        lod1: { file: "public/models/camera_xt_lod1.glb", sha256: sha("public/models/camera_xt_lod1.glb") } },
      look: look ?? "scripts/build/posters/look.js", margin: Number(margin), renderer: null,
      select: "stage.js posterSet(): the set of the LOD that pickLod() gives for the slot's contain rectangle at the canvas's effective DPR; the static tier shows lod0",
      bands: {},
    };
    for (const [band, framing] of Object.entries(framed.bands)) {
      const posters = {};
      for (const [lodKey, widths] of Object.entries(WIDTHS)) {
        posters[lodKey] = [];
        for (const w of widths) {
          const r = await runPage(context, origin, { mode: "poster", framing, w: String(w), lod: lodKey.slice(3), ...(lookUrl && { look: lookUrl }) });
          if (SOFTWARE.test(r.renderer) && !args.includes("--allow-software")) throw new Error(`software renderer: ${r.renderer}`);
          manifest.renderer = r.renderer;
          const png = Buffer.from(r.png.split(",")[1], "base64");
          const name = `camera-${band}${lodKey === "lod0" ? "" : `-${lodKey}`}-${w}`;
          if (args.includes("--png")) writeFileSync(join(out, `${name}.png`), png);
          const sizes = await encode(png, join(out, name));
          posters[lodKey].push({ w: r.w, h: r.h, avif: `${name}.avif`, webp: `${name}.webp`, ...sizes });
          console.log(`${name.padEnd(28)} ${r.w}x${r.h}  avif ${(sizes.avifBytes / 1024).toFixed(1)} kB  webp ${(sizes.webpBytes / 1024).toFixed(1)} kB`);
        }
      }
      manifest.bands[band] = { ...framing, posters };
    }
    writeFileSync(join(out, "posters.json"), JSON.stringify(manifest, null, 1) + "\n");
    console.log(`renderer: ${manifest.renderer}\nwrote ${join(out, "posters.json")}`);
  } finally {
    await browser.close();
    server.close();
  }
}

main().catch((e) => { console.error(e); process.exit(1); });
