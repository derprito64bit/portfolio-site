#!/usr/bin/env node
// Image stills (W-D026). content/ holds PNG or JPG masters only; the build derives one AVIF and one WebP still per
// print, cropped around focus{x,y}: 512 px long edge for the sheet, 1024 px for enlargements and the hero. Width,
// height and a tiny LQIP go into src/lib/content/stills.json; the files go to node_modules/.cache/portfolio-stills/
// and the Astro integration copies them to dist/stills/. The look bake (W-C2, scripts/build/looks) runs on top.
// While every project is a placeholder there is nothing to derive, and the manifest says so.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
export const CACHE = join(ROOT, 'node_modules/.cache/portfolio-stills');
const MANIFEST = join(ROOT, 'src/lib/content/stills.json');
const SIZES = { sheet: 512, large: 1024 };

function masters() {
  const projects = JSON.parse(readFileSync(join(ROOT, 'content/projects.json'), 'utf8')).projects;
  const out = [];
  projects.forEach((p, i) => {
    const imgs = [p.cover, ...p.media.filter((m) => m.type === 'image').map((m) => m.src)].filter(Boolean);
    for (const src of imgs) out.push({ slug: p.slug, src, focus: p.focus, large: i < 3 });
  });
  return out;
}

async function derive(list) {
  const sharp = (await import('sharp')).default;
  mkdirSync(CACHE, { recursive: true });
  const stills = [];
  for (const m of list) {
    const file = join(ROOT, 'content', m.src);
    if (!existsSync(file)) throw new Error(`images: ${m.src} is listed in content/projects.json but missing`);
    const input = readFileSync(file);
    const hash = createHash('sha256').update(input).digest('hex').slice(0, 12);
    for (const [kind, edge] of Object.entries(SIZES)) {
      if (kind === 'large' && !m.large) continue;
      const base = `${m.slug}-${kind}-${hash}`;
      const img = sharp(input).rotate().resize({ width: edge, height: edge, fit: 'inside', position: sharp.strategy.attention });
      const { info } = await img.clone().avif({ quality: 52, effort: 6 }).toFile(join(CACHE, `${base}.avif`));
      await img.clone().webp({ quality: 78, effort: 6 }).toFile(join(CACHE, `${base}.webp`));
      const lqip = await img.clone().resize(16).webp({ quality: 40 }).toBuffer();
      stills.push({ slug: m.slug, src: m.src, kind, width: info.width, height: info.height, avif: `/stills/${base}.avif`, webp: `/stills/${base}.webp`, lqip: `data:image/webp;base64,${lqip.toString('base64')}` });
    }
  }
  return stills;
}

const list = masters();
const stills = list.length ? await derive(list) : [];
const manifest = `${JSON.stringify({ schema: 1, note: 'generated by scripts/build/images.mjs; do not edit', stills }, null, 2)}\n`;
if (!existsSync(MANIFEST) || readFileSync(MANIFEST, 'utf8') !== manifest) writeFileSync(MANIFEST, manifest);
console.log(`images: ${list.length} masters, ${stills.length} stills${list.length ? '' : ' (every project is a placeholder)'}`);
