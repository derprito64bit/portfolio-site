#!/usr/bin/env node
// The image ladder for the owner's media (D-056, W-V1 spec A4). Originals live in the private portfolio-assets repo; this
// reads them from MEDIA_SRC (default ../portfolio-assets/media, next to this repo) and writes the derived files the site
// serves: AVIF and WebP at 480, 800, 1280 and 1920 px wide, never upscaled (src/lib/prints/ladder.ts), EXIF and GPS
// stripped, into public/media/<slug>/; video and model files are copied as they are and sized by their poster. The
// manifest, src/lib/content/media.json, keeps each original's real pixel size (the file wins over a typed w x h, D-042)
// and an LQIP of 300 B or less. The content PR runs it locally and commits public/media/ and media.json; the build itself needs
// no originals: without MEDIA_SRC it keeps the committed manifest. Placeholder media are scripts/build/media-fixtures.mjs.
// Usage: node scripts/build/images.mjs [--check]   (--check fails when the manifest is missing an entry)
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, extname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MEDIA_DIR, ladder } from '../../src/lib/prints/ladder.ts';
import { lqip } from './media-fixtures.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
export const DEFAULT_SRC = resolve(ROOT, '../portfolio-assets/media');
export const MANIFEST = join(ROOT, 'src/lib/content/media.json');
const NOTE = 'generated by scripts/build/images.mjs from the originals in portfolio-assets (D-056); do not edit';
const AVIF = { quality: 52, effort: 6 };
const WEBP = { quality: 78, effort: 6 };

/** The originals content/projects.json names: every non-placeholder media with a src, and each video's or model's
 *  poster. */
export function sources(projects) {
  const out = [];
  for (const p of projects) {
    p.media.forEach((m, k) => {
      if (m.placeholder || !m.src) return;
      if (m.type === 'video' || m.type === 'model') {
        out.push({ slug: p.slug, n: k + 1, src: m.src, kind: m.type, poster: m.poster });
        if (m.poster) out.push({ slug: p.slug, n: k + 1, src: m.poster, kind: 'poster' });
        if (m.type === 'video' && m.captions) out.push({ slug: p.slug, n: k + 1, src: m.captions, kind: 'captions' });
      } else if (m.type === 'image') {
        out.push({ slug: p.slug, n: k + 1, src: m.src, kind: 'image' });
      }
    });
  }
  return out;
}

/** The original's file under MEDIA_SRC: src is media/<slug>/<file>, MEDIA_SRC is the media folder itself. */
export const originalOf = (mediaSrc, src) => join(mediaSrc, src.replace(/^media\//, ''));
/** A site path under /media/ as a file under public/media (outDir). */
const outPath = (outDir, url) => join(outDir, url.replace(/^\/media\//, ''));

/** Real pixel size, after the EXIF orientation. */
export async function realSize(sharp, input) {
  const meta = await sharp(input).metadata();
  const swap = (meta.orientation ?? 1) >= 5;
  return { w: swap ? meta.height : meta.width, h: swap ? meta.width : meta.height };
}

/**
 * Derives every source into `outDir` (public/media) and returns the manifest. A source already in `prev` with the same
 * hash and its files on disk is kept as it is.
 */
export async function derive({ projects, mediaSrc, outDir, prev = { media: {} } }) {
  const sharp = (await import('sharp')).default;
  const media = {};
  for (const s of sources(projects)) {
    const file = originalOf(mediaSrc, s.src);
    if (!existsSync(file)) throw new Error(`images: ${s.src} is listed in content/projects.json but missing from ${mediaSrc}`);
    const input = readFileSync(file);
    const hash = createHash('sha256').update(input).digest('hex').slice(0, 10);
    const stem = `${basename(s.src, extname(s.src)).toLowerCase().replace(/[^a-z0-9]+/g, '-')}-${hash}`;
    const dir = MEDIA_DIR(s.slug);
    mkdirSync(join(outDir, s.slug), { recursive: true });
    const old = prev.media?.[s.src];
    if (s.kind === 'video' || s.kind === 'model' || s.kind === 'captions') {
      const url = `${dir}${stem}${extname(s.src).toLowerCase()}`;
      if (!existsSync(outPath(outDir, url))) copyFileSync(file, outPath(outDir, url));
      media[s.src] = s.kind === 'captions'
        ? { type: 'captions', hash, file: url, bytes: input.length }
        : { type: s.kind, hash, file: url, bytes: input.length, poster: s.poster };
      continue;
    }
    const { w, h } = await realSize(sharp, input);
    const files = ladder(dir, stem, w, h, { first: s.n === 1, poster: s.kind === 'poster' });
    const onDisk = files.every((f) => existsSync(outPath(outDir, f.avif)) && existsSync(outPath(outDir, f.webp)));
    if (old?.hash === hash && onDisk && old.files?.length === files.length) {
      media[s.src] = old;
      continue;
    }
    const img = sharp(input).rotate(); // the EXIF orientation applied; metadata (EXIF, GPS) is never written out
    for (const f of files) {
      const r = img.clone().resize({ width: f.rung, withoutEnlargement: true });
      await r.clone().avif(AVIF).toFile(outPath(outDir, f.avif));
      await r.clone().webp(WEBP).toFile(outPath(outDir, f.webp));
    }
    media[s.src] = { type: s.kind === 'poster' ? 'poster' : 'image', hash, w, h, files, lqip: await lqip(sharp, await img.clone().resize({ width: 64 }).toBuffer()) };
  }
  return { schema: 1, note: NOTE, media };
}

export const serialise = (m) => `${JSON.stringify(m, null, 2)}\n`;

/** The CLI: derive when originals are there, else keep the committed manifest. Returns a one-line summary. */
export async function main({ root = ROOT, mediaSrc = resolve(root, process.env.MEDIA_SRC || DEFAULT_SRC), manifest = join(root, 'src/lib/content/media.json'), outDir = join(root, 'public/media'), check = false } = {}) {
  const projects = JSON.parse(readFileSync(join(root, 'content/projects.json'), 'utf8')).projects;
  const prev = existsSync(manifest) ? JSON.parse(readFileSync(manifest, 'utf8')) : { schema: 1, media: {} };
  const list = sources(projects);
  const write = (m) => { if (!existsSync(manifest) || readFileSync(manifest, 'utf8') !== serialise(m)) writeFileSync(manifest, serialise(m)); };
  if (!list.length) {
    write({ schema: 1, note: NOTE, media: {} });
    return 'images: no owner media yet (every media entry is a placeholder; the build renders test charts)';
  }
  if (!existsSync(mediaSrc)) {
    const missing = list.filter((s) => !prev.media?.[s.src]);
    if (missing.length && check) throw new Error(`images: no originals at ${mediaSrc} and media.json lacks ${missing.map((s) => s.src).join(', ')}`);
    return `images: no originals at ${mediaSrc}; the committed media.json stands (${Object.keys(prev.media ?? {}).length} entries${missing.length ? `; ${missing.length} missing, which the content check names` : ''})`;
  }
  const next = await derive({ projects, mediaSrc, outDir, prev });
  write(next);
  return `images: ${list.length} originals from ${mediaSrc}, ${Object.keys(next.media).length} manifest entries`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    console.log(await main({ check: process.argv.includes('--check') }));
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
